
    /*
     * Represents a node in a Circular Singly Linked List.
     *
     * Each node contains:
     * 1. A value.
     * 2. A reference to the next node.
     *
     * Author: Muhammad Shoaib
     */

    public class Node {

        int value;
        Node next;

        public Node(int value) {
            this.value = value;
        }
    }


